namespace Valuify
{
    using System;
    using System.Collections.Generic;
    using System.Linq;
    using System.Text;
    using System.Threading;
    using Microsoft.CodeAnalysis;
    using Microsoft.CodeAnalysis.Text;

    /// <summary>
    /// Generates the Ignore attribute, used to denote when a property of a class should be ignored.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class IgnoreAttributeGenerator
        : IIncrementalGenerator
    {
        /// <summary>
        /// The name of the attribute (without the suffix).
        /// </summary>
        internal const string Name = "Ignore";

        /// <summary>
        /// The source code that will be output by the generator.
        /// </summary>
        internal static readonly string Content = string.Format(IgnoreAttributeGenerator_Resources.Content, Name);

        /// <summary>
        /// The hint name used for the code generated by the generator.
        /// </summary>
        internal static readonly string Hint = Name + "Attribute.g.cs";

        /// <inheritdoc/>
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(Generate);
        }

        private static void Generate(IncrementalGeneratorPostInitializationContext context)
        {
            var text = SourceText.From(Content, Encoding.UTF8);

            context.AddSource(Hint, text);
        }
    }
}