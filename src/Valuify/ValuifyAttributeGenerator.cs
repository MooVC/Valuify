namespace Valuify
{
    using System;
    using System.Text;
    using Microsoft.CodeAnalysis;
    using Microsoft.CodeAnalysis.Text;
    using MooVC.Syntax;
    using MooVC.Syntax.CSharp;
    using Attribute = System.Attribute;

    /// <summary>
    /// Generates the Valuify attribute, used to denote when a class should exhibit record-like behavior.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class ValuifyAttributeGenerator
        : IIncrementalGenerator
    {
        /// <summary>
        /// The name of the attribute (without the suffix).
        /// </summary>
        internal const string Name = "Valuify";

        /// <summary>
        /// The source code that will be output by the generator.
        /// </summary>
        internal static readonly string Content = CreateContent();

        /// <summary>
        /// The hint name used for the code generated by the generator.
        /// </summary>
        internal static readonly string Hint = Name + "Attribute.g.cs";

        /// <inheritdoc/>
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(Generate);
        }

        private static string CreateContent()
        {
            Symbol targets = typeof(AttributeTargets);

            return Builder
                .New<Definition>()
                .From(typeof(ValuifyAttributeGenerator))
                .For<Class>(attribute => attribute
                    .AttributedWith(usage => usage
                        .Named(typeof(AttributeUsageAttribute))
                        .WithArguments(
                            (Name: string.Empty, Value: $"{targets.ToSnippet(Configuration.Options.Types)}.Class"),
                            (Name: nameof(AttributeUsageAttribute.Inherited), Value: "false"),
                            (Name: nameof(AttributeUsageAttribute.AllowMultiple), Value: "false")))
                    .DerivesFrom(typeof(Attribute))
                    .IsPartial(false)
                    .Named($"{Name}Attribute")
                    .WithExtensibility(Modifiers.Sealed)
                    .WithScope(Scopes.Internal))
                .ToSnippet(Configuration.Options);
        }

        private static void Generate(IncrementalGeneratorPostInitializationContext context)
        {
            var text = SourceText.From(Content, Encoding.UTF8);

            context.AddSource(Hint, text);
        }
    }
}